// Inject the shared footer into index.html (replace the old block, or the previous generated block)
const idxPath = path.join(root, 'index.html');
let idx = fs.readFileSync(idxPath, 'utf8');
let start = idx.indexOf('<!-- FOOTER:START');
let endMarker = '<!-- FOOTER:END -->';
let end = start >= 0 ? idx.indexOf(endMarker) + endMarker.length : -1;
if (start < 0) {
  start = idx.indexOf('<footer class="site-footer">');
  end = idx.indexOf('</footer>') + '</footer>'.length;
}
if (start < 0 || end < start) throw new Error('footer block not found in index.html');
idx = idx.slice(0, start) + footer + idx.slice(end);
fs.writeFileSync(idxPath, idx);
